-- Convert the legacy serial ID columns and operational cursor to SQL-standard
-- identity columns. Run this before drizzle-kit push: adding an identity
-- sequence after push can collide with a serial sequence Drizzle just created.
-- The migration preserves existing rows and their generated-ID high-water mark.
DO $$
DECLARE
  target record;
  sequence_name text;
  max_value bigint;
BEGIN
  FOR target IN
    SELECT * FROM (VALUES
      ('action_items', 'id'),
      ('ai_conversation_turns', 'id'),
      ('ai_corrections', 'id'),
      ('ai_result_cache', 'id'),
      ('audit_logs', 'id'),
      ('background_operation_events', 'id'),
      ('cache_maintenance_events', 'id'),
      ('denied_merges', 'id'),
      ('duplicate_review_groups', 'id'),
      ('facility_knowledge', 'id'),
      ('factory_kv', 'id'),
      ('field_check_issues', 'id'),
      ('field_check_observations', 'id'),
      ('fill_missing_values', 'id'),
      ('freezer_surplus_adjustments', 'id'),
      ('import_aliases', 'id'),
      ('import_history', 'id'),
      ('ingredient_batch_weights', 'id'),
      ('inventory_items', 'id'),
      ('inventory_ledger', 'id'),
      ('inventory_locations', 'id'),
      ('inventory_lots', 'id'),
      ('inventory_observations', 'id'),
      ('inventory_product_references', 'id'),
      ('merge_aliases', 'id'),
      ('merged_away', 'id'),
      ('operational_intent_ledger', 'sequence'),
      ('photo_aliases', 'id'),
      ('production_runs', 'id'),
      ('qc_workflow_events', 'id'),
      ('quality_checks', 'id'),
      ('saved_cheese_sheets', 'id'),
      ('saved_premix_sheets', 'id'),
      ('saved_shipping_guides', 'id'),
      ('saved_spec_sheets', 'id'),
      ('spec_import_aliases', 'id'),
      ('sync_conflict_logs', 'id')
    ) AS columns_to_convert(table_name, column_name)
  LOOP
    IF EXISTS (
      SELECT 1
      FROM information_schema.columns
      WHERE table_schema = current_schema()
        AND table_name = target.table_name
        AND column_name = target.column_name
        AND is_identity = 'NO'
    ) THEN
      sequence_name := pg_get_serial_sequence(
        format('%I.%I', current_schema(), target.table_name),
        target.column_name
      );

      EXECUTE format(
        'ALTER TABLE %I.%I ALTER COLUMN %I DROP DEFAULT',
        current_schema(),
        target.table_name,
        target.column_name
      );

      IF sequence_name IS NOT NULL THEN
        EXECUTE format('DROP SEQUENCE %s', sequence_name);
      END IF;

      EXECUTE format(
        'ALTER TABLE %I.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
        current_schema(),
        target.table_name,
        target.column_name
      );

      EXECUTE format(
        'SELECT MAX(%I) FROM %I.%I',
        target.column_name,
        current_schema(),
        target.table_name
      ) INTO max_value;

      sequence_name := pg_get_serial_sequence(
        format('%I.%I', current_schema(), target.table_name),
        target.column_name
      );

      IF max_value IS NULL OR max_value < 1 THEN
        PERFORM setval(sequence_name::regclass, 1, false);
      ELSE
        PERFORM setval(sequence_name::regclass, max_value, true);
      END IF;
    END IF;
  END LOOP;
END $$;
