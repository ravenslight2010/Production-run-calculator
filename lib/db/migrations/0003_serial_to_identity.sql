-- Convert legacy serial-backed columns to SQL-standard BY DEFAULT identities.
-- Existing values are retained, and each sequence resumes above the current
-- maximum. Re-running this migration is safe.
DO $$
DECLARE
  migration_row record;
  sequence_value bigint;
  has_existing_value boolean;
BEGIN
  FOR migration_row IN
    SELECT *
    FROM (VALUES
      ('action_items', 'id'),
      ('ai_conversation_turns', 'id'),
      ('ai_corrections', 'id'),
      ('ai_result_cache', 'id'),
      ('audit_logs', 'id'),
      ('background_operation_events', 'id'),
      ('cache_maintenance_events', 'id'),
      ('denied_merges', 'id'),
      ('duplicate_review_groups', 'id'),
      ('facility_knowledge', 'id'),
      ('factory_kv', 'id'),
      ('field_check_issues', 'id'),
      ('field_check_observations', 'id'),
      ('fill_missing_values', 'id'),
      ('freezer_surplus_adjustments', 'id'),
      ('import_aliases', 'id'),
      ('import_history', 'id'),
      ('ingredient_batch_weights', 'id'),
      ('inventory_items', 'id'),
      ('inventory_ledger', 'id'),
      ('inventory_locations', 'id'),
      ('inventory_lots', 'id'),
      ('inventory_observations', 'id'),
      ('inventory_product_references', 'id'),
      ('merge_aliases', 'id'),
      ('merged_away', 'id'),
      ('operational_intent_ledger', 'sequence'),
      ('photo_aliases', 'id'),
      ('production_runs', 'id'),
      ('qc_workflow_events', 'id'),
      ('quality_checks', 'id'),
      ('saved_cheese_sheets', 'id'),
      ('saved_premix_sheets', 'id'),
      ('saved_shipping_guides', 'id'),
      ('saved_spec_sheets', 'id'),
      ('spec_import_aliases', 'id'),
      ('sync_conflict_logs', 'id')
    ) AS migration_targets(table_name, column_name)
  LOOP
    IF EXISTS (
      SELECT 1
      FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name = migration_row.table_name
        AND column_name = migration_row.column_name
        AND is_identity = 'NO'
    ) THEN
      EXECUTE format(
        'SELECT MAX(%I) FROM public.%I',
        migration_row.column_name,
        migration_row.table_name
      ) INTO sequence_value;
      has_existing_value := sequence_value IS NOT NULL;

      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN %I DROP DEFAULT',
        migration_row.table_name,
        migration_row.column_name
      );
      EXECUTE format(
        'DROP SEQUENCE IF EXISTS public.%I',
        migration_row.table_name || '_' || migration_row.column_name || '_seq'
      );
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
        migration_row.table_name,
        migration_row.column_name
      );
      EXECUTE format(
        'SELECT setval(pg_get_serial_sequence(%L, %L), $1, $2)',
        'public.' || migration_row.table_name,
        migration_row.column_name
      ) USING GREATEST(COALESCE(sequence_value, 1), 1), has_existing_value AND sequence_value >= 1;
    END IF;
  END LOOP;
END $$;
