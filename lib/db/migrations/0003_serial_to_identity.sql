-- 0003: convert legacy serial columns to SQL-standard identity columns.
-- Idempotent: skips columns already converted. Identity is BY DEFAULT (not
-- ALWAYS) so fixtures and imports may still insert explicit ids.
-- Each conversion rebases the identity sequence to MAX(col) so existing rows
-- can never collide with generated values.

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'action_items' AND column_name = 'id' AND is_identity = 'NO'
  ) THEN
    ALTER TABLE action_items ALTER COLUMN id DROP DEFAULT;
    DROP SEQUENCE IF EXISTS action_items_id_seq;
    ALTER TABLE action_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('action_items', 'id'),
                   GREATEST(COALESCE((SELECT MAX(id) FROM action_items), 0), 1));
  END IF;
END $$;

